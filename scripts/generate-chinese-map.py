#!/usr/bin/env python3
"""Regenerate src/Secondary.Core/ChineseData.cs from the OpenCC TS dictionary.

The generated table is checked in so builds need no network and no runtime
dependency. Only single BMP characters are used as char keys so parallel C#
strings stay index-aligned (UTF-16).

Source: https://github.com/BYVoid/OpenCC  data/dictionary/{TSCharacters,TSPhrases}.txt
License: Apache-2.0 (see third-party/OpenCC-LICENSE.txt).
"""
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "src", "Secondary.Core", "ChineseData.cs")


def read_dict(path):
    result = {}
    with io.open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) < 2:
                continue
            key = parts[0].strip()
            val = parts[1].split()[0].strip() if parts[1].strip() else ""
            if key and val and key != val:
                result[key] = val
    return result


def is_bmp_char(s):
    return len(s) == 1 and ord(s) <= 0xFFFF


def main(char_file, phrase_file):
    chars = read_dict(char_file)
    phrases = read_dict(phrase_file)
    char_items = [(k, v) for k, v in chars.items() if is_bmp_char(k) and is_bmp_char(v)]
    char_items.sort(key=lambda kv: ord(kv[0]))
    phrase_items = [(k, v) for k, v in phrases.items() if len(k) > 1 and all(is_bmp_char(c) for c in k + v)]
    phrase_items.sort(key=lambda kv: (-len(kv[0]), kv[0]))

    char_keys = "".join(k for k, _ in char_items)
    char_vals = "".join(v for _, v in char_items)
    assert len(char_keys) == len(char_vals)

    def cs(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    out = [
        "// <auto-generated>",
        "//   Generated from OpenCC TS dictionary (Apache-2.0).",
        "//   Source: https://github.com/BYVoid/OpenCC",
        "//   Regenerate with scripts/generate-chinese-map.py if needed.",
        "// </auto-generated>",
        "",
        "namespace Secondary.Core;",
        "",
        "internal static class ChineseData",
        "{",
        "    // Single-character traditional -> simplified pairs, parallel strings.",
        "    internal const string CharKeys = " + cs(char_keys) + ";",
        "    internal const string CharValues = " + cs(char_vals) + ";",
        "",
        "    // Multi-character phrases, longest first. Parallel arrays.",
        "    internal static readonly string[] PhraseKeys = new[]",
        "    {",
    ]
    out += ["        " + cs(k) + "," for k, _ in phrase_items]
    out += ["    };", "    internal static readonly string[] PhraseValues = new[]", "    {"]
    out += ["        " + cs(v) + "," for _, v in phrase_items]
    out += ["    };", "}"]

    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT, "-", len(char_items), "chars,", len(phrase_items), "phrases")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: generate-chinese-map.py TSCharacters.txt TSPhrases.txt")
    main(sys.argv[1], sys.argv[2])
